    sum(days) FILTER (WHERE kind = 'base') AS base,
    sum(days) FILTER (WHERE kind IN ('comp','carry')) AS comp
  FROM attendance_leave_grants WHERE year = 2026 AND status = 'active' AND source = 'excel' GROUP BY employee_id
),
cover AS (   -- 엑셀 날짜마다 그날을 덮는 승인 휴가(엑셀 이관 또는 남겨 둔 ERP 기록)
  SELECT u.name, u.day,
    max(CASE WHEN l.leave_type IN ('half_am','half_pm','half') THEN 0.5 WHEN l.leave_type IN ('annual','sick') THEN 1 ELSE 0 END) AS weight,
    count(l.id) AS n
  FROM excel_use u JOIN emp ON emp.name = u.name
  LEFT JOIN attendance_leaves l ON l.employee_id = emp.id AND l.status = 'approved' AND u.day BETWEEN l.start_date AND l.end_date
  GROUP BY u.name, u.day
