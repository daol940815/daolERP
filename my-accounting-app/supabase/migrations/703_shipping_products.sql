--
-- 배송비를 옵션 칩(702 의사 행)이 아니라 품목 마스터에 등록된 품목으로 관리한다.
-- 기본값: 판매가 0 (배송비는 판매가에 녹이는 경우가 대부분), 매입가만 기재 —
-- 주문 전환 시 일반 품목 행으로 그대로 넘어간다 (판매 0이라 매출 오염 없음,
-- 매입은 비용으로 정상 집계).
-- 702의 배송비 의사 행(품목 미연결)은 과거 저장분 호환용으로만 유지.
-- =====================================================

ALTER TABLE erp_products
  ADD COLUMN IF NOT EXISTS is_shipping BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN erp_products.is_shipping IS
  '배송비 품목 — 품목 마스터에서 수동 표시. 상담·주문 입력에서 같은 매입처 옵션 칩으로 노출, 선택 시 판매가 0 기본 (매입가만 기재).';
