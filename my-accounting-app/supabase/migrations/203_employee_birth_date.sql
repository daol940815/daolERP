-- 203_employee_birth_date.sql
-- 인사·총무 트랙 — 직원 생일
--
-- 스케줄 캘린더에 직원 생일을 표시한다(2026-10-14 사용자 요청 항목 ⑤).
-- 직원 마스터(employees) 컬럼 하나로 끝난다 — 새 테이블 없음.
--
-- 표시 규칙(코드): 재직자만, 월·일만 비교(연도 비노출), 2/29는 평년에 2/28.
-- 입력은 직원·계정·권한 화면(인사·총무 수정 권한). 본인은 내 정보에서 표시만
-- ("연락처만 본인 수정" 규칙 유지, 2026-10-01 사용자 확정).
-- =====================================================

ALTER TABLE employees ADD COLUMN IF NOT EXISTS birth_date DATE;

COMMENT ON COLUMN employees.birth_date IS
  '생일. 스케줄 캘린더 표시용(연도는 화면에 내지 않는다). 입력은 인사·총무.';
