-- 205_employee_work_phone.sql
-- 인사·총무 트랙 — 직원 업무용 핸드폰 번호
--
-- 2026-11-05 사용자 요청: 직원 정보에 업무용 핸드폰 번호를 추가하고,
-- 발주서의 "발주자 연락처"에는 업무용 번호가 들어가게 한다.
--
-- 규칙(코드):
--  - 기존 phone 은 개인 연락처로 그대로 둔다(본인이 내 정보에서 수정 — "연락처만 본인 수정").
--  - work_phone 은 인사·총무(직원 · 계정 · 권한)와 본인(내 정보 연락처 칸) 모두 입력한다
--    (2026-11-05 사용자 요청으로 본인 입력 허용 — 실행 후 코드만 바뀜, 재실행 불필요).
--  - 발주서 발주자 연락처 = 업무용 번호 → 없으면 직원 핸드폰(phone) → 없으면 회사 대표번호
--    (2026-11-05 사용자 결정으로 개인 번호 대체 추가).
-- 직원 마스터(employees) 컬럼 하나로 끝난다 — 새 테이블 없음.
-- =====================================================

ALTER TABLE employees ADD COLUMN IF NOT EXISTS work_phone TEXT;

COMMENT ON COLUMN employees.work_phone IS
  '업무용 핸드폰 번호. 발주서 발주자 연락처에 쓴다(없으면 회사 대표번호). 입력은 인사·총무.';
