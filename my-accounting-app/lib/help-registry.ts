// ── 조회 도우미 ──────────────────────────────────────────
const base = (href: string) => href.split('?')[0]
const tabOf = (href: string) => new URLSearchParams(href.split('?')[1] ?? '').get('tab')

// 현재 경로(+탭)에 맞는 항목: 탭까지 일치 → 경로 일치 → 가장 긴 접두(상세 화면 /orders/[id] → /orders)
export function findHelp(pathname: string, search?: string | null): HelpEntry | null {
  const tab = new URLSearchParams(search ?? '').get('tab')
  const exactTab = tab ? HELP.find(h => base(h.href) === pathname && tabOf(h.href) === tab) : null
  if (exactTab) return exactTab
  const exact = HELP.find(h => h.href === pathname || (base(h.href) === pathname && !tabOf(h.href)))
  if (exact) return exact
  const prefixed = HELP.filter(h => !tabOf(h.href) && base(h.href) !== '/' && pathname.startsWith(base(h.href) + '/')).sort((a, b) => b.href.length - a.href.length)
  return prefixed[0] ?? null
}
export const helpByHref = (href: string) => HELP.find(h => h.href === href) ?? null

// 최근 변경(HELP_RECENT_DAYS 이내)이 있는 항목의 기준 경로 → 최신 변경일
export function recentChangeMap(now = new Date()): Record<string, string> {
  const cutoff = new Date(now.getTime() - HELP_RECENT_DAYS * 86400_000).toISOString().slice(0, 10)
  const out: Record<string, string> = {}
  for (const h of HELP) {
    const latest = h.changes?.[0]?.date
    if (latest && latest >= cutoff) { const k = base(h.href); if (!out[k] || out[k] < latest) out[k] = latest }
  }
  return out
}

